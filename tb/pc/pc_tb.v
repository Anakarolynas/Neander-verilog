`timescale 1ns/1ps

// ============================================================
// NEANDER - Testbench do Program Counter
// Projeto: Processador Neander em Verilog
// Módulo: tb_pc
//
// Objetivo:
//   Testar as principais operações do PC:
//
//   1. Reset
//   2. carga
//   3. Incremento
//   4. Manutenção do valor
//
// Os resultados são impressos em forma de tabela.
// ============================================================

module tb_pc;

    // --------------------------------------------------------
    // Sinais de entrada
    // --------------------------------------------------------
    reg clk;
    reg rst;
    reg carga;
    reg inc;
    reg [7:0] din;

    // --------------------------------------------------------
    // Sinal de saída
    // --------------------------------------------------------
    wire [7:0] dout;


    // --------------------------------------------------------
    // Instância do módulo PC
    // --------------------------------------------------------
    pc dut (
        .clk(clk),
        .rst(rst),
        .carga(carga),
        .inc(inc),
        .din(din),
        .dout(dout)
    );


    // --------------------------------------------------------
    // Geração do clock
    //
    // O clock troca de estado a cada 5 ns.
    // Portanto, temos um período de 10 ns.
    // --------------------------------------------------------
    always #5 clk = ~clk;


    // --------------------------------------------------------
    // Impressão do cabeçalho da tabela
    // --------------------------------------------------------
    initial begin

        $display("");
        $display("==============================================================");
        $display("             TESTBENCH - PROGRAM COUNTER (PC)");
        $display("==============================================================");
        $display(" Tempo | rst | carga | inc | din |   PC");
        $display("-------+-----+------+-----+---------+--------");

    end


    // --------------------------------------------------------
    // Impressão dos resultados
    //
    // A cada mudança do PC, uma nova linha é impressa.
    // --------------------------------------------------------
    always @(dout) begin

        $display(" %5t |  %b  |  %b   |  %b  |   %02h    |  %02h",
                 $time,
                 rst,
                 carga,
                 inc,
                 din,
                 dout);

    end


    // --------------------------------------------------------
    // Sequência de testes
    // --------------------------------------------------------
    initial begin

        // ====================================================
        // Estado inicial
        // ====================================================

        clk     = 0;
        rst     = 1;
        carga    = 0;
        inc     = 0;
        din = 8'h00;


        // ====================================================
        // TESTE 1 - RESET
        //
        // Esperamos:
        // PC = 00
        // ====================================================

        #10;

        rst = 0;


        // ====================================================
        // TESTE 2 - carga
        //
        // Carrega o valor 10 hexadecimal no PC.
        //
        // 10h = 16 decimal
        // ====================================================

        din = 8'h10;
        carga = 1;

        #10;

        carga = 0;


        // ====================================================
        // TESTE 3 - INCREMENTO
        //
        // PC deve passar:
        //
        // 10 -> 11
        // ====================================================

        inc = 1;

        #10;


        // ====================================================
        // TESTE 4 - NOVO INCREMENTO
        //
        // PC deve passar:
        //
        // 11 -> 12
        // ====================================================

        #10;


        // ====================================================
        // TESTE 5 - MANTER VALOR
        //
        // Com inc = 0 e carga = 0,
        // o PC deve permanecer em 12.
        // ====================================================

        inc = 0;

        #10;


        // ====================================================
        // Finalização
        // ====================================================

        $display("==============================================================");
        $display("                 FIM DA SIMULACAO");
        $display("==============================================================");
        $display("");

        $finish;

    end

endmodule